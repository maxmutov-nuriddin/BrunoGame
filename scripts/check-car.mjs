import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import Physics from '../src/Physics.js';
import Car from '../src/World/Car.js';
import { findVehicle } from '../src/vehicles.js';
const vehicle = findVehicle(process.argv[2]);
const bytes = await readFile(new URL(`../public/models/${vehicle.file}`, import.meta.url));
const gltf = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
async function simulation(fps) {
  const physics = await Physics.create();
  physics.createBox({ position: new THREE.Vector3(0, -.25, 0), size: new THREE.Vector3(500, .5, 500) });
  const input = { throttle: 0, steer: 0, boost: false, brake: false };
  const app = { physics, vehicle, resources: { items: { [vehicle.resource]: gltf } }, scene: new THREE.Scene(), controls: { input, consumeJump: () => false }, triggerCrash() {} };
  const car = new Car(app);
  function run(seconds) { for(let i=0;i<Math.round(seconds*fps);i++) { physics.update(1/fps, dt => car.beforePhysics(dt)); car.afterPhysics(); } }
  run(3);
  assert.equal(car.getWheelContactCount(), 4, 'All wheels must settle on flat ground');
  assert.ok(car.position.y > .35 && car.position.y < .8, 'Chassis must rest on suspension');
  input.throttle = 1; run(5);
  const forwardZ = car.position.z, speed = car.speed;
  assert.ok(forwardZ < -10 && speed > 8, `Forward travel: z=${forwardZ}, speed=${speed}`);
  input.throttle = -1; run(.5);
  assert.ok(car.speed < speed, 'Opposite throttle must brake before reversing');
  input.throttle = 0; input.brake = true; run(3);
  assert.ok(car.speed < .5, `Brakes must stop the vehicle: ${car.speed}`);
  input.brake = false; input.throttle = -1; run(2);
  assert.ok(car.velocity.z > 1, 'Reverse must drive backwards');
  input.throttle = 1; input.steer = 1; run(4);
  assert.ok(Math.abs(car.position.x) > 1, 'Steering must change direction');
  assert.ok(car.group.quaternion.toArray().every(Number.isFinite));
  car.rigidBody.setRotation({x:0,y:0,z:1,w:0},true); car.recover();
  assert.ok(Math.abs(car.rigidBody.rotation().z) < .01, 'Recovery must upright the car');
  console.log(`${fps} FPS: forward z=${forwardZ.toFixed(3)}, speed=${speed.toFixed(3)}, steering x=${car.position.x.toFixed(3)}`);
  physics.world.free();
  return { forwardZ, speed };
}
const a=await simulation(30),b=await simulation(60),c=await simulation(120);
for(const result of [b,c]) assert.ok(Math.abs(a.forwardZ-result.forwardZ)<.02, 'Physics must be render-rate independent');
console.log('GLB loading, suspension, drive, braking, reverse, steering, recovery and frame-rate checks passed.');
